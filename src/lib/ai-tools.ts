export interface AITool {
  name: string
  slug: string
  tagline: string
  category: string
  pricing: "Free" | "Freemium" | "Paid"
  description: string
  featured: boolean
  rating: number
  affiliateLink?: string | null
  /**
   * True HANYA bila affiliateLink adalah URL afiliasi asli (membawa
   * ref/sub-ID program). Disclosure afiliasi dan rel sponsored
   * nofollow hanya aktif bila field ini true. Sembilan URL yang
   * ada di data saat ini (2026-11-04) adalah URL resmi biasa,
   * bukan afiliasi, jadi semuanya tetap false sampai link asli
   * dari program dimasukkan.
   */
  isAffiliateLink?: boolean
  /** Fitur utama, diisi per tool dari riset (opsional — disembunyikan bila kosong). */
  features?: string[]
  /** Kelebihan, diisi per tool dari riset (opsional). */
  pros?: string[]
  /** Kekurangan, diisi per tool dari riset (opsional). */
  cons?: string[]
  /**
   * Badge kurasi "Baru minggu ini" (definisi 2026-11-04): true hanya
   * untuk tool yang detailnya baru terisi penuh (fitur + pro + kontra)
   * dalam batch 7 hari terakhir, maksimal 1 batch. Batch baru
   * menggantikan batch lama; tool historis/sunset tidak ditandai
   * meski baru terisi, karena label "baru" akan menyesatkan.
   */
  newThisWeek?: boolean
  /**
   * Badge kurasi "Pilihan untuk UMKM" (definisi 2026-11-04): true
   * hanya bila tool terisi penuh, harganya Free/Freemium, kategorinya
   * non-Coding, dan rating di data situs >= 4.5.
   */
  curatedForUmkm?: boolean
}

/**
 * Tool dianggap terisi penuh bila fitur utama, kelebihan, dan kekurangan
 * sudah diisi dari riset. Tool yang belum terisi tidak diindeks dan tidak
 * masuk sitemap sampai dilengkapi, supaya direktori tidak dinilai dari
 * halaman detail yang hampir kosong.
 */
export function isToolContentFilled(tool: AITool): boolean {
  return (
    (tool.features?.length ?? 0) > 0 &&
    (tool.pros?.length ?? 0) > 0 &&
    (tool.cons?.length ?? 0) > 0
  )
}

